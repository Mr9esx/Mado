"""将同一份设备 SVG 资源导出为固件 A8 像素与离线原型符号。"""

import argparse
import io
import json
from pathlib import Path

import cairosvg
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
BEGIN = "<!-- BEGIN 由 firmware/tools/build_icons.py 生成。来源与许可证见 docs/iconpark-license.txt。 -->"
END = "<!-- END device-icons -->"


def raster(svg: str, size: int) -> bytes:
    document = f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 48 48" fill="none" color="black">{svg}</svg>'
    png = cairosvg.svg2png(bytestring=document.encode(), output_width=size, output_height=size)
    with Image.open(io.BytesIO(png)) as image:
        pixels = image.convert("RGBA").getchannel("A").tobytes()
    if len(pixels) != size * size or not any(pixels):
        raise ValueError(f"{size}px 图标没有生成有效的覆盖率")
    return pixels


def c_header(icons: dict) -> str:
    lines = [
        "// Generated by firmware/tools/build_icons.py from shared/device-icons.json.",
        "// IconPark SVG 1.4.2, Apache-2.0. See docs/iconpark-license.txt.",
        "#pragma once", "#include <stdint.h>", "",
        "typedef struct { const char *name; uint8_t size; const uint8_t *alpha; } td_icon_t;", "",
    ]
    index = []
    for name, info in icons.items():
        for size in info["sizes"]:
            pixels = raster(info["svg"], size)
            identifier = f"td_icon_{name.replace('-', '_')}_{size}"
            lines.append(f"static const uint8_t {identifier}[] = {{")
            for offset in range(0, len(pixels), size):
                row = ", ".join(f"0x{value:02x}" for value in pixels[offset:offset + size])
                lines.append(f"    {row},")
            lines.extend(["};", ""])
            index.append(f'    {{ "{name}", {size}, {identifier} }},')
    lines += ["static const td_icon_t td_icons[] = {", *index, "};", ""]
    return "\n".join(lines)


def prototype_html(original: str, icons: dict) -> str:
    prefix, begin, rest = original.partition(BEGIN)
    _, end, suffix = rest.partition(END)
    if not begin or not end:
        raise ValueError("原型缺少设备图标的生成标记")
    lines = [BEGIN, '<svg class="glyphs" xmlns="http://www.w3.org/2000/svg" aria-hidden="true">']
    for name, info in icons.items():
        svg = info["svg"]
        if name == "battery-empty":
            svg += '<rect x="7" y="19" height="10" fill="currentColor" style="width:var(--charge,0px)"/>'
        lines.append(f'  <symbol id="ip-{name}" viewBox="0 0 48 48">{svg}</symbol>')
    return prefix + "\n".join([*lines, "</svg>", END]) + suffix


def main(check: bool) -> None:
    icons = json.loads((ROOT / "shared/device-icons.json").read_text())
    prototype = ROOT / "docs/display-ui-prototype.html"
    outputs = {
        ROOT / "firmware/assets/device_icons.h": c_header(icons),
        prototype: prototype_html(prototype.read_text(), icons),
    }
    for path, contents in outputs.items():
        if check:
            if not path.exists() or path.read_text() != contents:
                raise SystemExit(f"图标输出过期：{path}")
        else:
            path.write_text(contents)
    print(f"校验通过：{len(icons)} 个图标，{sum(len(i['sizes']) for i in icons.values())} 个位图")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="验证生成产物与源一致")
    main(parser.parse_args().check)
