"""从品牌 SVG 生成 Logo RGBA 位图和名称 A8 蒙版；--check 检查产物。"""
import argparse
import io
from pathlib import Path

import cairosvg
from PIL import Image, ImageDraw, ImageFont
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[2]
SIZE = 36
WORDMARK_WIDTH, WORDMARK_HEIGHT = 50, 16
LOADING_TEXT = "资源加载中…"
LOADING_SIZE = 14
SLOGAN_TEXT = "自定义数据看板"
SLOGAN_SIZE = 12


def text_masks():
    # 固化文案，启动时无需等待设备字库分区读取或解压。
    with TTFont(ROOT / "src/assets/MapleMono-CN-Regular.woff2", recalcTimestamp=False) as font:
        missing = set(map(ord, LOADING_TEXT + SLOGAN_TEXT)) - set(font.getBestCmap())
        if missing:
            raise ValueError(f"启动文案缺字：{missing}")
        font.flavor = None
        sfnt = io.BytesIO()
        font.save(sfnt)
    for name, text, size in (("slogan", SLOGAN_TEXT, SLOGAN_SIZE),
                             ("loading", LOADING_TEXT, LOADING_SIZE)):
        font = ImageFont.truetype(io.BytesIO(sfnt.getvalue()), size)
        left, top, right, bottom = font.getbbox(text)
        mask = Image.new("L", (right - left, bottom - top))
        ImageDraw.Draw(mask).text((-left, -top), text, font=font, fill=255)
        yield name, text, size, mask


def generate():
    lines = ["// Generated by firmware/tools/build_brand.py. Do not edit.",
             "#pragma once", "#include <stdint.h>",
             f"static constexpr int td_brand_size = {SIZE};", ""]
    for theme in ("light", "dark"):
        png = cairosvg.svg2png(url=str(ROOT / f"public/brand/logo-{theme}.svg"),
                              output_width=SIZE, output_height=SIZE)
        with Image.open(io.BytesIO(png)) as image:
            pixels = list(image.convert("RGBA").get_flattened_data())
        lines.append(f"static const uint32_t td_brand_{theme}[] = {{")
        for offset in range(0, len(pixels), 8):
            lines.append("    " + ", ".join(
                f"0x{r:02x}{g:02x}{b:02x}{a:02x}" for r, g, b, a in pixels[offset:offset + 8]) + ",")
        lines += ["};", ""]
    png = cairosvg.svg2png(url=str(ROOT / "public/brand/wordmark.svg"),
                          output_width=WORDMARK_WIDTH, output_height=WORDMARK_HEIGHT)
    with Image.open(io.BytesIO(png)) as image:
        alpha = image.convert("RGBA").getchannel("A").tobytes()
    lines += [f"static constexpr int td_wordmark_width = {WORDMARK_WIDTH};",
              f"static constexpr int td_wordmark_height = {WORDMARK_HEIGHT};",
              "static const uint8_t td_wordmark_alpha[] = {"]
    for offset in range(0, len(alpha), 16):
        lines.append("    " + ", ".join(f"0x{a:02x}" for a in alpha[offset:offset + 16]) + ",")
    lines += ["};", ""]
    for name, text, size, mask in text_masks():
        alpha = mask.tobytes()
        lines += [f"// {text} — Maple Mono CN Regular, {size} px.",
                  f"static constexpr int td_{name}_width = {mask.width};",
                  f"static constexpr int td_{name}_height = {mask.height};",
                  f"static const uint8_t td_{name}_alpha[] = {{"]
        for offset in range(0, len(alpha), 16):
            lines.append("    " + ", ".join(f"0x{a:02x}" for a in alpha[offset:offset + 16]) + ",")
        lines += ["};", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = ROOT / "firmware/assets/brand_logo.h"
    contents = generate()
    if args.check:
        if not path.exists() or path.read_text() != contents:
            raise SystemExit("品牌位图过期，请运行 firmware/tools/build_brand.py")
    else:
        path.write_text(contents)
    print(f"品牌资源校验通过：两套 {SIZE} × {SIZE} Logo、{WORDMARK_WIDTH} × {WORDMARK_HEIGHT} 名称、slogan 及加载文案")
